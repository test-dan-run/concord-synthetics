// The persona panel puts the prompt stage 2 sent for a speaker next to the turns it produced (UI doc, "Persona
// panel"). The prompt is shown exactly as saved in prompts/<speaker_id>.txt, never rebuilt from a template.

import { useState } from "react";
import { Button, Chip, cx, Panel, Select, Spinner, Toggle } from "../../components/ui";
import { artifactUrl, type MeetingSpec, type Script, type ScriptValidation, type Timeline, useArtifact } from "../../lib/api";
import { DASH, hms, num } from "../../lib/format";

const TYPE_WORD: Record<string, string> = {
  normal: "normal",
  interruption: "interruption",
  backchannel: "backchannel",
  overlap_start: "overlap start",
  side: "side",
  presentation: "presentation",
};

/** Five turns around the persona's longest main turn, so the excerpt shows them talking with others. */
export function excerpt(script: Script, sid: string, size = 5): number[] {
  const own = script.turns.map((t, i) => [t, i] as const).filter(([t]) => t.speaker_id === sid);
  if (!own.length) return [];
  const main = own.filter(([t]) => t.interaction !== "backchannel");
  const [, anchor] = (main.length ? main : own).reduce((a, b) => (b[0].text.length > a[0].text.length ? b : a));
  const start = Math.max(0, Math.min(anchor - 2, script.turns.length - size));
  return Array.from({ length: Math.min(size, script.turns.length) }, (_, k) => start + k);
}

export function PersonaPanel({ run, m, selected, onSelect, script, validation, timeline }: {
  run: string;
  m: MeetingSpec;
  selected: string;
  onSelect: (id: string) => void;
  script: Script | null | undefined;
  validation: ScriptValidation | null | undefined;
  timeline: Timeline | null | undefined;
}) {
  const [view, setView] = useState<"text" | "text_norm">("text");
  const [copied, setCopied] = useState(false);
  const prompt = useArtifact<string>(run, m.meeting_id, `prompts/${selected}.txt`);
  const person = m.people.find((p) => p.speaker_id === selected);
  const score = validation?.primary?.scores.persona_consistency[selected];
  const starts = Object.fromEntries((timeline?.segments ?? []).map((s) => [s.turn_id, s.start]));
  const dropped = new Set(timeline?.dropped_turns ?? []);
  const idx = script ? excerpt(script, selected) : [];
  const shown = idx.map((i) => script!.turns[i]);
  const target = person ? Math.round(person.turn_share * m.dynamics.n_turns_target) : null;

  const copy = async () => {
    if (!prompt.data) return;
    try {
      await navigator.clipboard.writeText(prompt.data);
      setCopied(true);
      setTimeout(() => setCopied(false), 1500);
    } catch {
      setCopied(false);
    }
  };

  return (
    <Panel
      id="persona"
      title={`Persona · ${selected} ${person?.persona.role ?? ""}`}
      subtitle={
        script
          ? `Generated by ${script.generator.service} · template ${script.generator.template_version} · round ${script.generator.round} · judge persona consistency ${score !== undefined ? `${score.toFixed(1)} / 5` : DASH}`
          : "No script yet"
      }
      actions={
        <Select label="Persona" value={selected} onChange={(e) => onSelect(e.target.value)}>
          {m.people.map((p) => (
            <option key={p.speaker_id} value={p.speaker_id}>
              {p.speaker_id} · {p.persona.role}
            </option>
          ))}
        </Select>
      }
    >
      <div className="grid gap-4 min-[1000px]:grid-cols-2">
        <div className="flex flex-col gap-2 min-w-0">
          <div className="flex items-center gap-2">
            <span className="text-[11px] text-muted uppercase tracking-wider">Persona prompt</span>
            <Button size="sm" className="ml-auto" onClick={copy} disabled={!prompt.data}>
              {copied ? "Copied" : "Copy prompt"}
            </Button>
          </div>
          {prompt.isLoading ? (
            <Spinner label="Loading prompt" />
          ) : (
            <pre className="m-0 bg-canvas border border-track rounded-md p-3 text-xs leading-relaxed num whitespace-pre-wrap max-h-[420px] overflow-auto scroll-thin">
              {prompt.data ?? "No prompt saved for this speaker (stage 2 has not run)."}
            </pre>
          )}
          <span className="text-xs text-muted">
            Saved by stage 2 at <span className="num">prompts/{selected}.txt</span> and shown as saved.
          </span>
        </div>
        <div className="flex flex-col gap-2 min-w-0">
          <div className="flex items-center gap-2">
            <span className="text-[11px] text-muted uppercase tracking-wider">
              Sample from <span className="num normal-case">script.json</span>
            </span>
            <span className="ml-auto">
              <Toggle label="Script text form" value={view} onChange={(v) => setView(v as "text" | "text_norm")} options={[{ value: "text", label: "text" }, { value: "text_norm", label: "text_norm" }]} />
            </span>
          </div>
          {shown.length ? (
            <div className="border border-track rounded-md overflow-auto scroll-thin">
              <table className="w-full text-[13px] border-collapse">
                <caption className="sr-only">Turns around {selected} in the script</caption>
                <thead>
                  <tr className="border-b border-line text-left text-[11px] text-muted uppercase tracking-wider">
                    <th scope="col" className="px-3 py-2 font-medium">Time</th>
                    <th scope="col" className="px-3 py-2 font-medium">Speaker</th>
                    <th scope="col" className="px-3 py-2 font-medium">Type</th>
                    <th scope="col" className="px-3 py-2 font-medium">Turn</th>
                  </tr>
                </thead>
                <tbody>
                  {shown.map((t) => {
                    const own = t.speaker_id === selected;
                    return (
                      <tr key={t.turn_id} className={cx("border-b border-track last:border-0 align-top", own && "bg-active/60")}>
                        <td className="px-3 py-2 num text-muted whitespace-nowrap">{dropped.has(t.turn_id) ? "dropped" : hms(starts[t.turn_id])}</td>
                        <td className={cx("px-3 py-2 num", own ? "text-fg font-semibold" : "text-muted")}>{t.speaker_id}</td>
                        <td className="px-3 py-2">
                          <span className={cx(t.interaction === "overlap_start" && "hatch rounded")}>
                            <Chip>{TYPE_WORD[t.interaction] ?? t.interaction}</Chip>
                          </span>
                        </td>
                        <td className={cx("px-3 py-2", own ? "text-fg" : "text-muted", view === "text_norm" && "num text-xs")}>{t[view] || DASH}</td>
                      </tr>
                    );
                  })}
                </tbody>
              </table>
            </div>
          ) : (
            <span className="text-[13px] text-muted">{script ? `${selected} has no turns in the script.` : "No script yet."}</span>
          )}
          <div className="flex flex-wrap items-center gap-3 text-xs text-muted">
            <span className="num">
              {shown.length} turns shown · {shown.filter((t) => t.speaker_id === selected).length} by {selected} · target {target === null ? DASH : num(target)} in the full script
            </span>
            {script && (
              <a className="ml-auto" href={artifactUrl(run, m.meeting_id, "script.json")} target="_blank" rel="noreferrer">
                Open full script
              </a>
            )}
          </div>
        </div>
      </div>
    </Panel>
  );
}
